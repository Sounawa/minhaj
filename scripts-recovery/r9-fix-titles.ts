/** Normalisation : retire tashkīl/tatweel/nbsp, collapse les espaces. */
function norm(ar: string): string {
  return ar
    .replace(/&nbsp;/g, " ")
    .replace(/[\u064B-\u0652\u0670\u0640\u06D6-\u06ED]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

