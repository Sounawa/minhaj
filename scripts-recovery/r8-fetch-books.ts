async function fetchOne(docId: string, path: string, attempt = 1): Promise<void> {
  const url = `https://www-habous-gov-ma.translate.goog/${encodeURIComponent(path).replace(/%2F/g, "/")}.html?_x_tr_sl=ar&_x_tr_tl=fr`;
  try {
    const res = await fetch(url, { redirect: "follow" } as any);
    const html = await res.text();
    writeFileSync(`${OUT}/${docId}.html`, html, "utf-8");
    const ok = html.length > 50000 && html.includes("item-page");
    console.log(`${ok ? "✓" : "△"} ${docId}: ${res.status} ${html.length}B ${ok ? "item-page OK" : "CHECK CONTENT"}`);
  } catch (e) {
    if (attempt < 3) {
      await new Promise(r => setTimeout(r, 2000 * attempt));
      return fetchOne(docId, path, attempt + 1);
    }
    console.log(`✗ ${docId}: ${e instanceof Error ? e.message : e}`);
  }
}

async function main() {
  for (const [id, p] of pages) {
    if (existsSync(`${OUT}/${id}.html`)) { console.log(`- ${id}: déjà là`); continue; }
    await fetchOne(id, p);
    await new Promise(r => setTimeout(r, 900));
  }
}
main();
